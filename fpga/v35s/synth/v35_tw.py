"""(S7b) Write the timing wrapper's top (v35_tw_top) for one V35S core v2 module: its ports, read
from the module's header, cut from v35_tw_in's chain (inputs) and gathered onto v35_tw_out's
fold (outputs); `clock` is the wrapper's clock (clk_sys). Packed-struct ports take their width
from $bits of their type. Used by v35_timing.sh.

usage: v35_tw.py MODULE_FILE MODULE_NAME OUT_FILE
"""
import re
import sys

src, name, out = sys.argv[1:]
text = open(src).read()
m = re.search(r'\bmodule\s+' + re.escape(name) + r'\b(.*?)\);', text, re.S)
if not m:
    raise SystemExit(f'{name}: no module header in {src}')
head = m.group(1)
head = re.sub(r'//[^\n]*', '', head)
head = re.sub(r'/\*.*?\*/', '', head, flags=re.S)
# drop the import lines and a parameter list: the port list is the last (...) group
i = head.rfind('(')
j = head.find('(')
if '#' in head[:j]:
    # #(parameters) (ports
    depth, k = 0, head.index('#')
    k = head.index('(', k)
    for p in range(k, len(head)):
        depth += head[p] == '('
        depth -= head[p] == ')'
        if depth == 0:
            break
    head = head[p + 1:]
ports_txt = head[head.index('(') + 1:]
ports = []                       # (dir, width_expr, name)
cur_dir, cur_w = None, None
for item in [x.strip() for x in ports_txt.split(',')]:
    if not item:
        continue
    mm = re.match(r'(input|output)\s+(.*)$', item, re.S)
    if mm:
        cur_dir = mm.group(1)
        rest = mm.group(2).strip()
        toks = rest.split()
        pname = toks[-1]
        decl = ' '.join(toks[:-1])
        decl = re.sub(r'\b(wire|reg|logic)\b', '', decl).strip()
        decl = decl.replace('signed', '').strip()
        mw = re.match(r'\[([^:\]]+):0\]$', decl)
        if decl == '':
            cur_w = '1'
        elif mw:
            cur_w = f'({mw.group(1)}) + 1'
        elif re.match(r'^[A-Za-z_]\w*$', decl):
            cur_w = f'$bits({decl})'
        else:
            raise SystemExit(f'{name}: cannot read the port declaration "{item}"')
    else:
        pname = item.split()[-1]
    if cur_dir is None:
        raise SystemExit(f'{name}: a port before its direction: {item}')
    ports.append((cur_dir, cur_w, pname))

ins = [p for p in ports if p[0] == 'input' and p[2] != 'clock']
outs = [p for p in ports if p[0] == 'output']
L = []
L.append('`timescale 1ns/1ps')
L.append(f'// generated by fpga/v35s/synth/v35_tw.py for {name} ({src.split("/")[-1]})')
L.append('module v35_tw_top')
L.append('    import v35_front_pkg::*;')
L.append('    import v35_pkg::*;')
L.append('(')
L.append('    (* syn_peri_port = 0 *) input wire clk_sys,   // the PLL\'s output (not a GPIO)')
L.append('    input  wire       si,')
L.append('    output wire [7:0] xo')
L.append(');')
off = '0'
for d, w, n in ins:
    L.append(f'    localparam int IW_{n} = {w};')
    L.append(f'    localparam int IO_{n} = {off};')
    off = f'IO_{n} + IW_{n}'
L.append(f'    localparam int NI = {off};')
off = '0'
for d, w, n in outs:
    L.append(f'    localparam int OW_{n} = {w};')
    L.append(f'    localparam int OO_{n} = {off};')
    off = f'OO_{n} + OW_{n}'
L.append(f'    localparam int NO = {off};')
L.append('    wire [NI-1:0] in_q;')
L.append('    wire [NO-1:0] out_d;')
L.append('    v35_tw_in #(.N(NI)) tw_in (.clock(clk_sys), .si, .q(in_q));')
L.append(f'    {name} dut (')
conns = []
for d, w, n in ports:
    if n == 'clock':
        conns.append('        .clock(clk_sys)')
    elif d == 'input':
        conns.append(f'        .{n}(in_q[IO_{n} +: IW_{n}])')
    else:
        conns.append(f'        .{n}(out_d[OO_{n} +: OW_{n}])')
L.append(',\n'.join(conns))
L.append('    );')
L.append('    v35_tw_out #(.N(NO)) tw_out (.clock(clk_sys), .d(out_d), .xo);')
L.append('endmodule')
open(out, 'w').write('\n'.join(L) + '\n')
print(f'{name}: {len(ins)} inputs, {len(outs)} outputs -> {out}')
