`timescale 1ns/1ps

// V35S core v2: the execution unit's datapath (docs/v35s-core-v2.md, "Function path"; stage
// S3: the register classes; the memory classes' request path is S2's single-slot post, S4
// widens it). The sequencer (v35_ucode.sv) times the form; this module gives it its
// function: the operands from the register RAM (v35_regram.sv: port A the operand A /
// result register, port B the operand B, the EA's base or SP), the immediates and the
// displacement from the loader's take bytes, the read data from the delivery (rd), the
// result and the PSW into the registers, the requests' addresses and write data, the
// segment registers, the shift count and MUL's sign clocks the rows read.
//
// What a form does comes from its format word only (v35_pkg::v35_fmt_t, generated by
// validation/v35s/chains/ucgen.py): the operation `xop` (with `aop`), the operand roles `opa`
// (the destination / first operand) and `opb` (the source / second), the width `wd`, `nwr`
// (flags only), `sx` (a sign-extended immediate byte), `stk` (the stack forms), the ModR/M
// fields and `mem`. No opcode byte is compared here; a register named in the opcode's bits
// 2:0 (role OPR) or a segment in its bits 4:3 (role SOP) is read from the opcode byte as a
// field.
//
// The register RAM's read addresses are registered at `ce`: on every clock this module
// names the registers the next clock's form reads (S6: the running form's, or, when no form
// runs next clock, the decode ahead's: the IR's format as v35_loader decodes it a clock
// early). A form's register function runs on its "exec" clock: a register form's when its
// last operand byte is taken (a form without operand bytes: its start clock), a memory
// form's (and a load / POP / IN's) at its read's delivery, a stack form's stack pointer at
// its post. When the ports did not hold its operands on that clock (its ModR/M byte was not
// known a clock ahead) it runs a clock later (exec_pend). Results are written at `ce` (one
// write per clock; a second, MUL's DW or XCH's other register, the next clock).
//
// The segment registers are kept in flops as well (written through to the RAM): every memory
// address needs one besides the two offset registers the ports give (the plan's ps_shadow,
// extended to DS0 / DS1 / SS). CW is kept in a flop too (the sequencer's count source: the
// shift loop's CL, a start's cnt0 decided a clock ahead).
//
// Stage map: S2 (T) / S5 (P): the start latches the form, the takes collect its bytes, the
// exec's function and the posts' requests are combinational from the registers, the ports
// and this clock's bytes; S6: the writes, the next clock's port addresses.
//
// Registered state (widths) and the model variables it replaces:
//   fmt 121, op 8, pc 20                   the running form (decoder / eu.pc)
//   pfx 3, seg_o 3                         eu.seg_prefix (the next form's), the running form's
//   ob 6 x 8, nob 3                        the operand bytes taken (templates.decode's code)
//   exec_done 1, exec_pend 1               the register function ran / waits a clock
//   aim_ea 1                               the ports hold the EA's registers (v35_ea.sv holds
//                                          ea_bi, the base + index latched)
//   rd_lo 8                                an odd word's first half (its low byte)
//   sp_done 1                              the running stack form posted its SP request
//   pa_r 4, pb_r 4                         the registers the RAM ports hold this clock
//   rd 16                                  the read datum (v35_deliver's md)
//   res 16                                 an RMW's result (the write datum)
//   psw 16, ds1 ds0 ss ps 16 each, cw 16   the PSW, the segment registers, CW (regs dict)
//   w2_v 1, w2_a 7, w2_be 2, w2_d 16       the second register write
//   dv 1, ds 75 (v35_div_t), dvp 1,        the divider (v35_div's iteration state; DIV's exec
//   dv_d 16, dv_lo 16                      latched the divisor and AW, DW the next clock)
//   (S5a) rq0 rq1 rq2 16 each, nrd 4       the running form's reads in order (a far pointer's
//                                          words, RET's / RETI's / BRK's: op.target, the PSW)
//   tgt 16                                 BR / CALL r16's target (op.target)
//   nsp 3                                  the stack posts the running form made (PUSH R)
//   ix 16, iy 16, dcw 1, dix 1, diy 1      the string unit: IX, IY (regs dict; CW is cw), their
//                                          RAM copies stale (written through when free)
//   srd_iy 1, srd_ovr 1, sdst 16           the string read in flight is [IY], an overrun read;
//                                          an element's first read's datum (the compare's,
//                                          the BCD pair's source)
//   bi 8, bcy 1, bz 1, bres 8              a BCD string's pair index, carry, zero term, result
module v35_eu
    import v35_front_pkg::*;
    import v35_pkg::*;
    import v35_fn_pkg::*;
(
    input  wire        clock,
    input  wire        reset_n,
    input  wire        ce,

    // the starts (S2 T, S5 P) and the IR they start from
    input  wire        t_start,
    input  wire        p_start,
    input  v35_fmt_t   fmt_c,
    input  wire [7:0]  ir_c,
    input  wire [19:0] ir_addr_c,
    input  v35_fmt_t   fmt_l,
    input  v35_fmt_t   fmt_mt,          // the form re-decoded at a T ModR/M take (the loader's)
    input  v35_fmt_t   fmt_mp,          // ... at a P one
    input  wire [7:0]  ir_l,
    input  wire [19:0] ir_addr_l,
    // the takes: T's bytes (the head window), P's byte (after T's and the IR load)
    input  wire [7:0]  vb0, vb1, vb2, vb3,
    input  wire [1:0]  t_k,
    input  wire        l_pop,
    input  wire        p_k,
    // the sequencer's next state
    input  wire        run_e,
    input  wire        aim_next,        // the running form reads no register next clock
    input  v35_fmt_t   fmt_e,
    input  wire        t_flush,
    // the decode ahead (the next clock's form when none runs)
    input  wire        nf_v,
    input  v35_fmt_t   nf_fmt,
    input  wire [7:0]  nf_op,
    // the posts
    input  wire        post_t,
    input  uc_row_t    prow_t,
    input  wire [6:0]  psetup_t,
    input  wire        pfnv_t,
    input  wire [6:0]  pfn_t,
    input  wire [1:0]  plead_t,
    input  wire        post_p,
    input  uc_row_t    prow_p,
    input  wire [6:0]  psetup_p,
    input  wire        pfnv_p,
    input  wire [6:0]  pfn_p,
    input  wire [1:0]  plead_p,
    input  req_t       ptm_t,           // the posts' window fields (the sequencer's)
    input  req_t       ptm_p,
    // the own request's read delivered (its last cycle ended on t-1)
    input  wire        own_done,
    input  wire        own_two,         // ... an odd word's pair (hi, then lo)
    input  wire [2:0]  dlv_kind,
    input  wire [19:0] dlv_addr,
    input  wire [1:0]  dlv_width,
    input  wire [15:0] dlv_data,
    // the register RAM
    output wire [6:0]  ra_next,
    output wire        wa_en,
    output wire [6:0]  wa_addr,
    output wire [1:0]  wa_be,
    output wire [15:0] wa_data,
    input  wire [15:0] ra_data,
    output wire [6:0]  rb_next,
    input  wire [15:0] rb_data,

    // the requests (the arbiter's records)
    output req_t       rq_t,
    output req_t       rq_p,
    // the running form's memory operand address and write datum, as a request posted before
    // its displacement or its result issues reads them (the arbiter)
    output wire [19:0] ea_live,
    output wire [15:0] wd_live,
    output wire [15:0] wd_imm,          // the immediate after T's takes (store_imm's datum, B2)
    // the sequencer's counts
    output wire [8:0]  cnt,
    output wire [7:0]  cl_c,
    output wire [7:0]  cl_e,
    output wire [15:0] psw_c,           // (S5a) the PSW and CW now / after this clock (the
    output wire [15:0] psw_e,           //   transfers' start-time decision, the decode ahead's)
    output wire [15:0] cw_c,
    output wire [15:0] cw_e,
    // (S5a) the strings: the sequencer's element strobe and overrun posts, the loop's exits
    input  wire        edone,           // a REP element's last row completed (CW counted down)
    input  wire        povr_t,          // the T / P post is a REP compare's overrun read
    input  wire        povr_p,
    output wire        str_last,        // the REP loop's last element by count (CW = 1)
    output wire        str_exit,        // the compare ended the REP loop on its condition now
    output wire [3:0]  mneg,
    // a transfer's target (the flush), the SFR store's datum
    output wire [19:0] t_flush_addr,
    output wire [15:0] sfr_data,
    // the trace
    output wire [19:0] pc_o,
    output wire        miss_o           // a register write lost on this clock (a third)
);
    // ------------------------------------------------------------ registered state
    v35_fmt_t  fmt = '0;
    reg [7:0]  op = 8'h00;
    reg [19:0] pc = 20'hFFFF0;
    reg [2:0]  pfx = 3'd0;              // the segment prefix the next form carries (seg code)
    reg [2:0]  seg_o = 3'd0;            // the running form's
    reg [47:0] ob = 48'd0;              // operand bytes, ob[8j +: 8] the j-th
    reg [2:0]  nob = 3'd0;
    reg        exec_done = 1'b0;
    reg        exec_pend = 1'b0;
    reg        aim_ea = 1'b0;
    reg [7:0]  rd_lo = 8'd0;
    reg        sp_done = 1'b0;          // the running stack form's SP post made
    reg [3:0]  pa_r = 4'd0;             // {valid, REG16 index} the ports hold this clock
    reg [3:0]  pb_r = 4'd0;
    reg [15:0] rd = 16'd0;
    reg [15:0] res = 16'd0;
    reg [15:0] psw = 16'hF002;
    reg [15:0] ds1 = 16'd0, ds0 = 16'd0, ss = 16'd0, ps = 16'hFFFF;
    reg [15:0] cw = 16'd0;
    reg        w2_v = 1'b0;
    reg [6:0]  w2_a = 7'd0;
    reg [1:0]  w2_be = 2'd0;
    reg [15:0] w2_d = 16'd0;
    reg        dv = 1'b0;
    v35_div_t  ds = '0;
    reg        dvp = 1'b0;              // DIV's exec ran: the dividend's high half next
    reg [15:0] dv_d = 16'd0, dv_lo = 16'd0;
    // (S5a) the running form's read data in order (a far pointer's offset and segment, RET's
    // return address, RETI's PSW, POP R's words) and the transfer's register target
    reg [15:0] rq0 = 16'd0, rq1 = 16'd0, rq2 = 16'd0;
    reg [3:0]  nrd = 4'd0;              // the own reads delivered in the running form
    reg [15:0] tgt = 16'd0;             // BR / CALL r16's target (the register at its exec)
    reg [2:0]  nsp = 3'd0;              // the stack posts made in the running form (PUSH R)
    wire [15:0] ea_off_w, ea_seg_w;     // (v35_ea: the offset of the form after T, its segment)
    wire        ea_ok_t;                // (S5a) ... its base and index were on the ports (LDEA)
    // (S5a) the string unit: IX and IY as flops (CW's already), stepped by the width at each
    // element's request post (DIR: down; not a REP compare's overrun read), CW counted down per
    // REP element; written through to the register RAM on a clock its write port is free
    reg [15:0] ix = 16'd0, iy = 16'd0;
    reg        dcw = 1'b0, dix = 1'b0, diy = 1'b0;  // the RAM's copy is stale
    reg        srd_iy = 1'b0;           // the string read posted last is the destination's [IY]
    reg        srd_ovr = 1'b0;          // ... a REP compare's overrun read (nothing compared)
    reg [15:0] sdst = 16'd0;            // an element's first read's datum (CMPBK's [IY], a BCD
                                        // string's source byte [IX + i])
    // (S5a) the BCD strings (ADD4S / SUB4S / CMP4S): the byte pair's index (IX and IY stay),
    // the carry / borrow and the zero term across the pairs
    reg [7:0]  bi = 8'd0;
    reg        bcy = 1'b0, bz = 1'b1;
    reg [7:0]  bres = 8'd0;               // ... the pair's result (its write posted after the delivery)

    localparam logic [2:0] R_AW = 3'd0, R_CW = 3'd1, R_DW = 3'd2, R_BW = 3'd3, R_SP = 3'd4,
                           R_BP = 3'd5, R_IX = 3'd6, R_IY = 3'd7;

    /* verilator lint_off UNUSEDSIGNAL */
    // the RAM word of a register: REG16[i] at slot 1Eh - 2i, the segment register s (0 DS1,
    // 1 PS, 2 SS, 3 DS0) at slot 0Eh - 2s; the bank PSW.RB
    function automatic logic [6:0] rword(input logic [2:0] bank, input logic [2:0] i);
        rword = {bank, 4'(4'd15 - {1'b0, i})};
    endfunction
    function automatic logic [6:0] sword(input logic [2:0] bank, input logic [1:0] s);
        sword = {bank, 4'(4'd7 - {2'd0, s})};
    endfunction

    // the register a role names (REG16 index of the word; the byte register's half from the
    // index's bit 2 when the operation is a byte one): {valid, index 3}
    function automatic logic [3:0] role_reg(input logic [3:0] role, input v35_fmt_t f,
                                            input logic [7:0] o);
        case (role)
            V35_ROLE_RF: role_reg = {1'b1, f.rfield};
            V35_ROLE_RM: role_reg = (f.mem && f.has_modrm && f.md != 2'd3) || (f.mem && !f.has_modrm)
                                    ? 4'd0 : {1'b1, f.rm};
            V35_ROLE_OPR: role_reg = {1'b1, o[2:0]};
            V35_ROLE_ACC: role_reg = {1'b1, R_AW};
            default: role_reg = 4'd0;
        endcase
    endfunction
    // the word register holding a register operand of width w (a byte register k: REG16[k & 3])
    function automatic logic [3:0] wreg(input logic [3:0] rr, input logic w);
        wreg = rr[3] ? {1'b1, w ? rr[2:0] : {1'b0, rr[1:0]}} : 4'd0;
    endfunction

    // the segment register by index (0 DS1, 1 PS, 2 SS, 3 DS0)
    function automatic logic [15:0] segv(input logic [1:0] s);
        case (s)
            2'd0: segv = ds1;
            2'd1: segv = ps;
            2'd2: segv = ss;
            default: segv = ds0;
        endcase
    endfunction

    // the immediate (the bytes after the ModR/M byte and its displacement): a word, or a
    // byte (sign-extended with sx)
    function automatic logic [15:0] immv(input v35_fmt_t f, input logic [47:0] b);
        int k;
        logic [7:0] lo, hi;
        k = (f.page != 2'd0 ? 1 : 0) + (f.has_modrm ? 1 : 0) + int'(f.disp);
        lo = b[8 * k +: 8];
        hi = b[8 * (k + 1) +: 8];
        if (f.immb == 2'd2)
            immv = {hi, lo};
        else if (f.sx)
            immv = {{8{lo[7]}}, lo};
        else
            immv = {8'd0, lo};
    endfunction
    /* verilator lint_on UNUSEDSIGNAL */

    // ------------------------------------------------------------ S2/S5: this clock's form
    // the start (T or P) and the bytes taken this clock, in order
    wire        st_t = t_start;
    wire        st_p = p_start;
    wire [7:0]  pb_byte = t_k == 2'd0 ? (l_pop ? vb1 : vb0) : (t_k == 2'd1 ? (l_pop ? vb2 : vb1)
                                                               : (l_pop ? vb3 : vb2));
    // after the T pass (a T start, T's take) ...
    v35_fmt_t    f_t;
    logic [7:0]  o_t;
    logic [19:0] pc_t;
    logic [47:0] ob_t;
    logic [2:0]  nob_t;
    always_comb begin
        f_t = fmt;
        o_t = op;
        pc_t = pc;
        ob_t = ob;
        nob_t = nob;
        if (st_t) begin
            f_t = fmt_c;
            o_t = ir_c;
            pc_t = ir_addr_c;
            ob_t = 48'd0;
            nob_t = 3'd0;
        end
        if (t_k != 2'd0) begin
            ob_t[8 * nob_t +: 8] = vb0;
            if (t_k == 2'd2)
                ob_t[8 * (nob_t + 3'd1) +: 8] = vb1;
        end
        nob_t = nob_t + {1'b0, t_k};
        // the ModR/M byte taken now: the format as it decodes (the start decoded the head
        // byte; the loader's re-decode)
        if (!st_t && f_t.has_modrm && t_k != 2'd0 && nob_t == {1'b0, t_k})
            f_t = fmt_mt;
    end
    // ... and after the P pass: the form this clock
    v35_fmt_t    f_now;
    logic [7:0]  o_now;
    logic [19:0] pc_now;
    logic [47:0] ob_now;
    logic [2:0]  nob_now;
    logic        new_form;
    always_comb begin
        f_now = f_t;
        o_now = o_t;
        pc_now = pc_t;
        ob_now = ob_t;
        nob_now = nob_t;
        new_form = st_t;
        if (st_p) begin
            f_now = fmt_l;
            o_now = ir_l;
            pc_now = ir_addr_l;
            ob_now = 48'd0;
            nob_now = 3'd0;
            new_form = 1'b1;
        end
        if (p_k) begin
            ob_now[8 * nob_now +: 8] = pb_byte;
            nob_now = nob_now + 3'd1;
        end
        if (!st_p && f_now.has_modrm && p_k && nob_now == 3'd1)
            f_now = fmt_mp;
    end

    // the register values the ports hold (the second write still pending forwarded)
    wire [6:0]  pa_w = rword(psw[14:12], pa_r[2:0]);
    wire [6:0]  pb_w = rword(psw[14:12], pb_r[2:0]);
    wire [15:0] ra_v = (w2_v && w2_a == pa_w) ? {w2_be[1] ? w2_d[15:8] : ra_data[15:8],
                                                  w2_be[0] ? w2_d[7:0] : ra_data[7:0]} : ra_data;
    wire [15:0] rb_v = (w2_v && w2_a == pb_w) ? {w2_be[1] ? w2_d[15:8] : rb_data[15:8],
                                                  w2_be[0] ? w2_d[7:0] : rb_data[7:0]} : rb_data;

    // a word register's value now ({ok, value}: a port holds it; CW from its flop)
    /* verilator lint_off UNUSEDSIGNAL */
    function automatic logic [16:0] rget(input logic [3:0] wr);
        if (!wr[3])
            rget = {1'b1, 16'd0};
        else if (wr[2:0] == R_CW)       // (S5a) CW, IX, IY: the flops
            rget = {1'b1, cw};
        else if (wr[2:0] == R_IX)
            rget = {1'b1, ix};
        else if (wr[2:0] == R_IY)
            rget = {1'b1, iy};
        else if (pa_r[3] && pa_r[2:0] == wr[2:0])
            rget = {1'b1, ra_v};
        else if (pb_r[3] && pb_r[2:0] == wr[2:0])
            rget = {1'b1, rb_v};
        else
            rget = {1'b0, 16'd0};
    endfunction
    // a register operand (rr from role_reg) of width w: {ok, value} (a byte in the low byte)
    function automatic logic [16:0] rop(input logic [3:0] rr, input logic w);
        logic [16:0] v;
        v = rget(wreg(rr, w));
        if (rr[3] && !w)
            rop = {v[16], 8'd0, rr[2] ? v[15:8] : v[7:0]};
        else
            rop = v;
    endfunction

    // an operand by role: {ok, value}
    function automatic logic [16:0] opnd(input logic [3:0] role, input v35_fmt_t f,
                                         input logic [7:0] o, input logic [47:0] b,
                                         input logic [15:0] mdat);
        logic [3:0] rr;
        rr = role_reg(role, f, o);
        case (role)
            V35_ROLE_RF, V35_ROLE_OPR, V35_ROLE_ACC: opnd = rop(rr, f.wd);
            V35_ROLE_RM: opnd = rr[3] ? rop(rr, f.wd) : {1'b1, f.wd ? mdat : {8'd0, mdat[7:0]}};
            V35_ROLE_IMM: opnd = {1'b1, immv(f, b)};
            V35_ROLE_ONE: opnd = {1'b1, 16'd1};
            V35_ROLE_CL: opnd = {1'b1, 8'd0, cw[7:0]};
            V35_ROLE_SRF: opnd = {1'b1, segv(f.rfield[1:0])};
            V35_ROLE_SOP: opnd = {1'b1, segv(o[4:3])};
            default: opnd = {1'b1, 16'd0};
        endcase
    endfunction
    /* verilator lint_on UNUSEDSIGNAL */

    // ------------------------------------------------------------ the exec: the register
    // function of a form (the register forms at their exec clock; a memory form, a load,
    // POP, IN at the read's delivery with mdat the datum)
    typedef struct packed {
        logic        ok;        // the operands were on the ports
        logic        w1;        // the first write: wreg {valid, index}, its value
        logic [3:0]  r1;
        logic [15:0] v1;
        logic        w2;        // the second write
        logic [3:0]  r2;
        logic [15:0] v2;
        logic        sg;        // a segment register written
        logic [1:0]  sgi;
        logic [15:0] sgv;
        logic        pw;        // the PSW written
        logic [15:0] pv;
        logic        rv;        // the result kept (an RMW's write datum)
        logic [15:0] res;
        logic        dstart;    // the divider starts
        logic        tg;        // (S5a) a register transfer's target latched (tgt)
        logic [15:0] tgv;
        logic        scmp;      // (S5a) a string compare's result (the REP exit's flags)
    } ex_t;

    // a register write of width w into the word register of rr: (word, byte enables, data)
    /* verilator lint_off UNUSEDSIGNAL */
    function automatic logic [20:0] wput(input logic [3:0] rr, input logic w,
                                         input logic [15:0] v);
        logic [3:0] wr;
        wr = wreg(rr, w);
        if (w)
            wput = {wr[2:0], 2'b11, v};
        else if (rr[2])
            wput = {wr[2:0], 2'b10, v[7:0], 8'd0};
        else
            wput = {wr[2:0], 2'b01, 8'd0, v[7:0]};
    endfunction

    function automatic ex_t exec(input v35_fmt_t f, input logic [7:0] o, input logic [47:0] b,
                                 input logic [15:0] mdat, input logic [3:0] ri);
        ex_t x;
        logic [16:0] a, bb;
        logic [15:0] r, pw;
        logic [31:0] p;
        logic [3:0] ra, rb;
        logic [16:0] spv, bpv, awv;
        x = '0;
        a = opnd(f.opa, f, o, b, mdat);
        bb = opnd(f.opb, f, o, b, mdat);
        ra = role_reg(f.opa, f, o);
        rb = role_reg(f.opb, f, o);
        x.ok = a[16] && bb[16];
        pw = psw;
        case (f.xop)
            V35_XOP_ALU: begin
                r = v35_alu(f.aop, f.wd, a[15:0], bb[15:0], psw, pw);
                x.pw = 1'b1;
                x.pv = pw;
                if (!f.nwr) begin
                    x.w1 = ra[3];
                    x.r1 = ra;
                    x.v1 = r;
                    x.rv = 1'b1;
                    x.res = r;
                end
            end
            V35_XOP_MOV: begin
                x.w1 = ra[3];
                x.r1 = ra;
                x.v1 = bb[15:0];
                x.rv = 1'b1;
                x.res = bb[15:0];
            end
            V35_XOP_XCH: begin
                x.w1 = ra[3];
                x.r1 = ra;
                x.v1 = bb[15:0];
                x.w2 = rb[3];
                x.r2 = rb;
                x.v2 = a[15:0];
                x.rv = 1'b1;
                x.res = a[15:0];
            end
            V35_XOP_SHIFT: begin
                r = v35_shift(f.aop, f.wd, a[15:0], bb[8:0], psw, pw);
                x.pw = 1'b1;
                x.pv = pw;
                x.w1 = ra[3];
                x.r1 = ra;
                x.v1 = r;
                x.rv = 1'b1;
                x.res = r;
            end
            V35_XOP_MUL: begin
                p = v35_mul(f.sgn, f.wd, a[15:0], bb[15:0], psw, pw);
                x.pw = 1'b1;
                x.pv = pw;
                x.w1 = 1'b1;
                x.r1 = {1'b1, R_AW};
                x.v1 = p[15:0];
                x.w2 = f.wd;
                x.r2 = {1'b1, R_DW};
                x.v2 = p[31:16];
            end
            V35_XOP_MULI: begin
                p = v35_mul(1'b1, 1'b1, bb[15:0], immv(f, b), psw, pw);
                x.pw = 1'b1;
                x.pv = pw;
                x.w1 = ra[3];
                x.r1 = ra;
                x.v1 = p[15:0];
            end
            V35_XOP_DIV: x.dstart = 1'b1;       // the divider runs (v35_div_step per clock)
            // (S5a) DBNZ / DBNZE / DBNZNE: CW counted down at the displacement's take
            V35_XOP_LOOP: begin
                x.w1 = 1'b1;
                x.r1 = {1'b1, R_CW};
                x.v1 = cw - 16'd1;
            end
            // (S5a) BR / CALL r16: the target register at the operand take
            V35_XOP_JMP, V35_XOP_CALL: begin
                x.tg = f.aop == V35_XK_REG;
                x.tgv = a[15:0];
            end
            // (S5a) LES / LDS: the offset word into the register, the segment word into DS1 / DS0
            V35_XOP_LPTR: begin
                if (ri == 4'd0) begin
                    x.w1 = ra[3];
                    x.r1 = ra;
                    x.v1 = mdat;
                end else begin
                    x.sg = 1'b1;
                    x.sgi = f.aop[1:0];
                    x.sgv = mdat;
                end
            end
            // (S5a) POP R: the words IY IX BP (SP's discarded) BW DW CW AW, read from SP up
            V35_XOP_POPR: begin
                x.w1 = ri != 4'd3;
                x.r1 = {1'b1, 3'(3'd7 - ri[2:0])};
                x.v1 = mdat;
            end
            // (S5a) PREPARE imm16,0 (after BP's push): BP := SP, SP := SP - imm16
            V35_XOP_PREP: begin
                spv = rget({1'b1, R_SP});
                x.w1 = 1'b1;
                x.r1 = {1'b1, R_BP};
                x.v1 = spv[15:0];
                x.w2 = 1'b1;
                x.r2 = {1'b1, R_SP};
                x.v2 = spv[15:0] - immv(f, b);
                x.ok = spv[16];
            end
            // (S5a) DISPOSE (its read at BP): BP := the word, SP := BP + 2
            V35_XOP_DISP: begin
                bpv = rget({1'b1, R_BP});
                x.w1 = 1'b1;
                x.r1 = {1'b1, R_BP};
                x.v1 = mdat;
                x.w2 = 1'b1;
                x.r2 = {1'b1, R_SP};
                x.v2 = bpv[15:0] + 16'd2;
                x.ok = bpv[16];
            end
            // (S5a) the adjusts, the conversions (AW)
            V35_XOP_ADJ: begin
                awv = rget({1'b1, R_AW});
                p = v35_adjust(f.aop[1:0], awv[15:0], psw);
                x.pw = 1'b1;
                x.pv = p[31:16];
                x.w1 = 1'b1;
                x.r1 = {1'b1, R_AW};
                x.v1 = p[15:0];
                x.ok = awv[16];
            end
            V35_XOP_CVTBD: begin                // AH := AL / imm, AL := AL mod imm
                awv = rget({1'b1, R_AW});
                if (b[7:0] != 8'd0) begin
                    x.w1 = 1'b1;
                    x.r1 = {1'b1, R_AW};
                    x.v1 = {awv[7:0] / b[7:0], awv[7:0] % b[7:0]};
                    x.pw = 1'b1;
                    x.pv = v35_szp(psw, {8'd0, awv[7:0] % b[7:0]}, 1'b0);
                end
                x.ok = awv[16];
            end
            // (S5a) the strings at a read's delivery: LDM loads AL / AW; CMPBK keeps [IY], then
            // compares [IX] - [IY]; CMPM compares AW - [IY] (a REP compare's overrun read: none)
            V35_XOP_STR: if (!srd_ovr) begin
                awv = rget({1'b1, R_AW});
                case (f.aop)
                    V35_STR_LDM: begin
                        x.w1 = 1'b1;
                        x.r1 = {1'b1, R_AW};
                        x.v1 = mdat;
                    end
                    V35_STR_CMPBK, V35_STR_CMPM: if (!(f.aop == V35_STR_CMPBK && srd_iy)) begin
                        void'(v35_alu(3'd7, f.wd, f.aop == V35_STR_CMPBK ? mdat
                                                  : (f.wd ? awv[15:0] : {8'd0, awv[7:0]}),
                                      f.aop == V35_STR_CMPBK ? sdst : mdat, psw, pw));
                        x.pw = 1'b1;
                        x.pv = pw;
                        x.scmp = 1'b1;
                        x.ok = awv[16];
                    end
                    default: ;
                endcase
            end
            // (S5a) LDEA: the memory operand's offset (the EA unit's, after T) into the register
            V35_XOP_LDEA: begin
                x.w1 = ra[3];
                x.r1 = ra;
                x.v1 = ea_off_w;
                x.ok = ea_ok_t;
            end
            // (S5a) a BCD string's destination byte read: the pair's result (written back by
            // ADD4S / SUB4S), the PSW of the string so far (CY S AC the carry, Z P the zero term)
            V35_XOP_BCD: if (srd_iy) begin
                x.pw = 1'b1;
                x.pv = psw;
                x.pv[V35_PSW_CY] = bcd_r[9];
                x.pv[V35_PSW_S] = bcd_r[9];
                x.pv[V35_PSW_AC] = bcd_r[9];
                x.pv[V35_PSW_V] = 1'b0;
                x.pv[V35_PSW_Z] = bz && bcd_r[8];
                x.pv[V35_PSW_P] = bz && bcd_r[8];
            end
            V35_XOP_CVTDB: begin                // AL := AH * imm + AL, AH := 0
                awv = rget({1'b1, R_AW});
                r = {8'd0, 8'(awv[15:8] * b[7:0] + awv[7:0])};
                x.w1 = 1'b1;
                x.r1 = {1'b1, R_AW};
                x.v1 = r;
                x.pw = 1'b1;
                x.pv = v35_szp(psw, r, 1'b0);
                x.ok = awv[16];
            end
            V35_XOP_INC, V35_XOP_DEC: begin
                r = v35_alu(f.xop == V35_XOP_DEC ? 3'd5 : 3'd0, f.wd, a[15:0], 16'd1, psw, pw);
                pw[V35_PSW_CY] = psw[V35_PSW_CY];
                x.pw = 1'b1;
                x.pv = pw;
                x.w1 = ra[3];
                x.r1 = ra;
                x.v1 = r;
                x.rv = 1'b1;
                x.res = r;
            end
            V35_XOP_NOT: begin
                x.w1 = ra[3];
                x.r1 = ra;
                x.v1 = ~a[15:0];
                x.rv = 1'b1;
                x.res = ~a[15:0];
            end
            V35_XOP_NEG: begin
                r = v35_alu(3'd5, f.wd, 16'd0, a[15:0], psw, pw);
                x.pw = 1'b1;
                x.pv = pw;
                x.w1 = ra[3];
                x.r1 = ra;
                x.v1 = r;
                x.rv = 1'b1;
                x.res = r;
            end
            V35_XOP_SRLD: begin
                x.sg = 1'b1;
                x.sgi = f.rfield[1:0];
                x.sgv = bb[15:0];
            end
            V35_XOP_SRST: begin
                x.w1 = ra[3];
                x.r1 = ra;
                x.v1 = bb[15:0];
                x.rv = 1'b1;
                x.res = bb[15:0];
            end
            V35_XOP_POP: begin                  // (at the read's delivery) the register
                if (f.opa == V35_ROLE_SOP) begin
                    x.sg = 1'b1;
                    x.sgi = o[4:3];
                    x.sgv = mdat;
                end else begin
                    x.w1 = ra[3];
                    x.r1 = ra;
                    x.v1 = mdat;
                    x.rv = 1'b1;
                    x.res = mdat;
                end
            end
            V35_XOP_POPF: begin                 // the flags; MD and RB stay (the prelude's
                x.pw = 1'b1;                    // POP PSW leaves RB 7: init_s's F002h)
                x.pv = {psw[15:12], mdat[11:0]};
            end
            V35_XOP_IN: begin
                x.w1 = 1'b1;
                x.r1 = {1'b1, R_AW};
                x.v1 = f.wd ? mdat : {8'd0, mdat[7:0]};
            end
            V35_XOP_XLAT: begin
                x.w1 = 1'b1;
                x.r1 = {1'b1, R_AW};
                x.v1 = {8'd0, mdat[7:0]};
            end
            V35_XOP_CVTBW: begin
                x.w1 = 1'b1;
                x.r1 = {1'b1, R_AW};
                x.v1 = {{8{a[7]}}, a[7:0]};
            end
            V35_XOP_CVTWL: begin
                x.w1 = 1'b1;
                x.r1 = {1'b1, R_DW};
                x.v1 = {16{a[15]}};
            end
            V35_XOP_FLAG: begin
                x.pw = 1'b1;
                x.pv = psw;
                case (f.aop)
                    3'd0: x.pv[V35_PSW_CY] = 1'b0;
                    3'd1: x.pv[V35_PSW_CY] = 1'b1;
                    3'd2: x.pv[V35_PSW_CY] = !psw[V35_PSW_CY];
                    3'd3: x.pv[V35_PSW_IE] = 1'b0;
                    3'd4: x.pv[V35_PSW_IE] = 1'b1;
                    3'd5: x.pv[V35_PSW_DIR] = 1'b0;
                    default: x.pv[V35_PSW_DIR] = 1'b1;
                endcase
            end
            V35_XOP_LAHF: begin
                x.w1 = 1'b1;
                x.r1 = {1'b1, 3'd4};            // AH: byte register 4
                x.v1 = {8'd0, psw[7:0]};
            end
            V35_XOP_SAHF: begin
                x.pw = 1'b1;
                x.pv = {psw[15:8], a[15:8]};
            end
            default: ;                          // the transfers, the stack and I/O writes, the
        endcase                                 // 0F page, the strings: S4 / S5 (PUSH's SP
        return x;                               // is the post's)
    endfunction
    /* verilator lint_on UNUSEDSIGNAL */

    // ------------------------------------------------------------ when the exec runs
    // a register form (not a memory form, not a delivery form): its last operand byte taken
    // now, or its start for a form without operand bytes; or a pending one
    // (LDEA: no bus cycle, its exec at its last operand byte as a register form's)
    wire        delivery_form = (f_now.mem && f_now.bus) || f_now.xop == V35_XOP_POP
                                || f_now.xop == V35_XOP_POPF
                                || f_now.xop == V35_XOP_IN || f_now.xop == V35_XOP_XLAT
                                || f_now.xop == V35_XOP_POPR || f_now.xop == V35_XOP_DISP
                                || f_now.xop == V35_XOP_STR || f_now.xop == V35_XOP_BCD;
    wire        all_taken = nob_now >= f_now.len - 3'd1 - (f_now.page != 2'd0 ? 3'd1 : 3'd0);
    wire        ex_reg = !delivery_form && (new_form ? all_taken : (!exec_done && all_taken))
                         || exec_pend;
    // a read delivered for the own request (the last cycle of a word: S2's single cycle)
    // (own_done here is the arbiter's own_dlv strobe: the datum on the bus's delivery clock)
    wire        rd_now = own_done && k_read(dlv_kind) && dlv_kind != K_FETCH;
    wire        rd_half = k_read(dlv_kind) && dlv_kind != K_FETCH && dlv_width == BW_HI
                          && own_two && !own_done;     // the pair's first half (hi lane)
    wire [15:0] rd_dat = own_two ? {dlv_data[7:0], rd_lo}
                       : (dlv_width == BW_WORD) ? dlv_data
                       : {8'd0, (dlv_width == BW_HI || dlv_addr[0]) ? dlv_data[15:8]
                                                                     : dlv_data[7:0]};
    wire        ex_mem = rd_now && delivery_form;
    ex_t        xr;
    always_comb begin
        xr = exec(f_now, o_now, ob_now, ex_mem ? rd_dat : rd, nrd);
        if (!(ex_reg || ex_mem))
            xr = '0;
    end
    wire        ex_go = (ex_reg || ex_mem) && xr.ok;
    wire        ex_wait = ex_reg && !xr.ok;     // the operands not on the ports: next clock

    // the divider: DIV's exec latches the divisor and AW (the ports); on the next clock DW
    // (port A) and the dividend's set up; then a step per clock
    wire [16:0] dv_hi = rget({1'b1, R_DW});
    wire [16:0] dv_aw = rget({1'b1, R_AW});
    wire [16:0] dv_op = opnd(f_now.opb, f_now, o_now, ob_now, ex_mem ? rd_dat : rd);
    v35_div_t   ds_n;
    always_comb begin
        ds_n = ds;
        if (dvp)
            ds_n = v35_div_init(fmt.sgn, fmt.wd, fmt.wd ? {dv_hi[15:0], dv_lo} : {16'd0, dv_lo},
                                dv_d);
        else if (dv)
            ds_n = v35_div_step(ds);
    end
    logic [15:0] dpsw;
    logic        dtrap;
    wire [31:0]  dres = v35_div_fin(ds_n, psw, dpsw, dtrap);
    wire         dfin = dv && ds.n == 5'd1;          // the last step this clock

    // ------------------------------------------------------------ the requests
    // the address of a post's request, its datum, its width
    /* verilator lint_off UNUSEDSIGNAL */
    function automatic req_t mkreq(input uc_row_t r, input logic [6:0] setup,
                                   input logic fnv, input logic [6:0] fn, input logic [1:0] lead,
                                   input req_t tm, input v35_fmt_t f, input logic [7:0] o,
                                   input logic [47:0] b, input logic [19:0] pcx);
        req_t q;
        logic [15:0] sp_v, d;
        logic [16:0] spr, bpr;
        logic [7:0] vt;
        q = tm;                         // the window fields (through, imm1, floors, ...)
        case (r.rkind)
            V35_RK_READ: q.kind = K_READ;
            V35_RK_WRITE, V35_RK_NOWRITE: q.kind = K_WRITE;   // (NOWRITE: the slot)
            V35_RK_IO_READ: q.kind = K_IO_READ;
            V35_RK_IO_WRITE: q.kind = K_IO_WRITE;
            default: q.kind = K_NONE;
        endcase
        q.nowrite = r.rkind == V35_RK_NOWRITE;
        spr = rget({1'b1, R_SP});
        sp_v = spr[15:0];
        // the memory operand (v35_ea.sv): the running form's own request takes its address as
        // it issues (posted before the displacement was taken: pop_mem's write)
        case (r.asrc)
            V35_ASRC_EA: begin
                q.addr = ea_phys + {16'd0, r.aidx, 1'b0};
                q.alive = !r.detached;
                q.aoff = r.aidx;
            end
            // (S5a) a stack word: SP moves at every stack post (sp_post), so the i-th word of a
            // burst (aidx) is at the SP the earlier posts left
            V35_ASRC_SPW: q.addr = {ss, 4'd0} + {4'd0, sp_v - 16'd2};
            V35_ASRC_SPR: q.addr = {ss, 4'd0} + {4'd0, sp_v};
            V35_ASRC_PORT_IMM: q.addr = {12'd0, b[7:0]};
            V35_ASRC_PORT_DW: q.addr = {4'd0, rb_v};
            V35_ASRC_BP: begin                  // (S5a) DISPOSE's read at SS:BP
                bpr = rget({1'b1, R_BP});
                q.addr = {ss, 4'd0} + {4'd0, bpr[15:0]};
            end
            // (S5a) a string element: the source DS0:IX (a prefix's segment), the destination
            // DS1:IY
            V35_ASRC_STR_IX: q.addr = {seg_o != 3'd0 && seg_o <= 3'd4 ? segv(2'(seg_o - 3'd1))
                                                                      : ds0, 4'd0}
                                      + {4'd0, ix + (f.xop == V35_XOP_BCD ? {8'd0, bi} : 16'd0)};
            V35_ASRC_STR_IY: q.addr = {ds1, 4'd0}
                                      + {4'd0, iy + (f.xop == V35_XOP_BCD ? {8'd0, bi} : 16'd0)};
            V35_ASRC_VEC: begin                 // (S5a) BRK's vector words at 0:4n (+2)
                vt = f.aop != 3'd0 ? {5'd0, f.aop} : b[7:0];
                q.addr = {10'd0, vt, 2'b00} + {16'd0, r.aidx, 1'b0};
            end
            default: q.addr = 20'd0;        // IX, IY, the strings
        endcase
        // the datum: the form's write value (its source register, the immediate, the PSW,
        // a segment register, an RMW's result, a return address)
        d = wdatum(f, o, b, r.aidx, pcx, sp_v);
        // an RMW's result, POP's datum: the running form's own write takes its datum as it
        // issues (the exec at the read's delivery registers it on that clock's edge)
        q.dlive = !r.detached && wd_res(f);
        q.dimm = !r.detached && f.xop == V35_XOP_MOV && f.opb == V35_ROLE_IMM;
        q.data = (q.kind == K_IO_WRITE && !(r.wsel == V35_WSEL_WORD || (r.wsel == V35_WSEL_FMT && f.w)))
                 ? {d[7:0], d[7:0]} : d;
        if (r.wsel == V35_WSEL_WORD || (r.wsel == V35_WSEL_FMT && f.w))
            q.width = BW_WORD;
        else
            q.width = q.addr[0] ? BW_HI : BW_LO;
        if (q.kind == K_WRITE && q.width == BW_HI)
            q.data = {d[7:0], 8'd0};
        q.setup = setup;
        q.fn_v = fnv;                   // (the sequencer's: the row's, or the class's)
        q.fn = fn;
        q.lead = lead;
        q.port = r.asrc == V35_ASRC_PORT_IMM;
        q.detached = r.detached;
        q.grp = r.grp;
        // (S5a) io_count=nowait (an I/O request; dwlike: str_count / burst_count = dw, the
        // format's dw_count), str_in_io=free (the sequencer's memc), a string's class
        q.dwl = f.dw_count;
        q.nwt = (q.kind == K_IO_READ || q.kind == K_IO_WRITE || f.dw_count) && !tm.memc;
        q.strc = f.strop;
        return q;
    endfunction

    // the datum is the result register's (not a register operand read at the post)
    function automatic logic wd_res(input v35_fmt_t f);
        case (f.xop)
            V35_XOP_PUSH, V35_XOP_PUSHF, V35_XOP_OUT, V35_XOP_MOV, V35_XOP_SRST, V35_XOP_CALL,
            V35_XOP_BRK, V35_XOP_PUSHR, V35_XOP_PREP, V35_XOP_STR: wd_res = 1'b0;
            default: wd_res = 1'b1;
        endcase
    endfunction
    // the datum a form writes (memory, the stack, a port)
    function automatic logic [15:0] wdatum(input v35_fmt_t f, input logic [7:0] o,
                                           input logic [47:0] b, input logic [2:0] ai,
                                           input logic [19:0] pcx, input logic [15:0] spx);
        logic [16:0] v;
        logic [15:0] ipn;
        // (S5a) the return address: the next instruction's offset in PS
        ipn = 16'(pcx - {ps, 4'd0}) + 16'(f.len);
        case (f.xop)
            // CALL near: the return offset; CALL far: PS, then the return offset
            V35_XOP_CALL: v = {1'b1, (ai == 3'd0 && (f.aop == V35_XK_FAR || f.aop == V35_XK_MEMFAR))
                                     ? ps : ipn};
            // BRK: PSW, PS, the return offset
            V35_XOP_BRK: v = {1'b1, ai == 3'd0 ? psw : (ai == 3'd1 ? ps : ipn)};
            // PUSH R: AW CW DW BW SP (as it stood before the burst) BP IX IY
            V35_XOP_PUSHR: v = ai == R_SP ? {1'b1, spx + 16'd8} : rget({1'b1, ai});
            V35_XOP_PREP: v = rget({1'b1, R_BP});
            // (S5a) STM: AL / AW; MOVBK, INM, OUTM: the element's read datum (its write posted
            // on the read's delivery clock)
            V35_XOP_STR: v = f.aop == V35_STR_STM ? rop({1'b1, R_AW}, f.wd)
                                                   : {1'b1, rd_now ? rd_dat : rd};
            V35_XOP_BCD: v = {1'b1, 8'd0, rd_now ? bcd_r[7:0] : bres};   // (S5a) the pair's result
            V35_XOP_PUSH: v = opnd(f.opb, f, o, b, rd);
            V35_XOP_PUSHF: v = {1'b1, psw};
            V35_XOP_OUT: v = rop({1'b1, R_AW}, 1'b1);
            V35_XOP_MOV, V35_XOP_SRST: v = opnd(f.opb, f, o, b, rd);
            default: v = {1'b1, res};       // an RMW's result (its read's delivery)
        endcase
        wdatum = v[15:0];
    endfunction
    /* verilator lint_on UNUSEDSIGNAL */

    assign rq_t = mkreq(prow_t, psetup_t, pfnv_t, pfn_t, plead_t, ptm_t, f_t, o_t, ob_t, pc_t);
    assign rq_p = mkreq(prow_p, psetup_p, pfnv_p, pfn_p, plead_p, ptm_p, f_now, o_now, ob_now,
                        pc_now);
    // the live address and datum (an RMW's result after its read's delivery: res, registered)
    assign ea_live = ea_phys;
    assign wd_live = res;
    wire [15:0] imm_t = immv(f_t, ob_t);
    assign wd_imm = f_t.w ? imm_t : {imm_t[7:0], imm_t[7:0]};

    // (S5a) a BCD string's byte pair: the destination byte (the read delivered now, or the last
    // read's) with the source byte, the carry in; {carry, zero term, result}
    wire [7:0]  bcd_a = rd_now ? rd_dat[7:0] : rd[7:0];
    wire [9:0]  bcd_r = v35_bcd8(fmt.aop != 3'd0, bcd_a, sdst[7:0], bcy);
    // the stack pointer of a stack form's post: SP - 2 (a push), SP + 2 (a pop) at the post
    // (S5a) every stack post moves SP (the burst's words, CALL far's, BRK's, RET far's)
    wire        sp_post = (post_t && (prow_t.asrc == V35_ASRC_SPW || prow_t.asrc == V35_ASRC_SPR))
                          || (post_p && (prow_p.asrc == V35_ASRC_SPW
                                         || prow_p.asrc == V35_ASRC_SPR));
    wire        sp_dn = post_t ? prow_t.asrc == V35_ASRC_SPW : prow_p.asrc == V35_ASRC_SPW;
    wire [16:0] sp_rd = rget({1'b1, R_SP});
    wire [15:0] sp_new = sp_dn ? sp_rd[15:0] - 16'd2 : sp_rd[15:0] + 16'd2;
    wire        sp_done_n = sp_post || (sp_done && !new_form);
    // (S5a) the stack posts the running form has made (PUSH R's next word)
    wire [2:0]  nsp_n = (new_form ? 3'd0 : nsp) + (sp_post ? 3'd1 : 3'd0);

    // ------------------------------------------------------------ the sequencer's counts
    // (the rows that read them, CNT and UNIT, follow the form's operand takes: the registered
    // form and bytes)
    wire [16:0] cnt_v = opnd(fmt.opb, fmt, op, ob, rd);
    assign cnt = fmt.xop == V35_XOP_SHIFT ? cnt_v[8:0] : 9'd0;
    // MUL r/m16 (F7 /5): the operands' signs differing: 8, a clock more with the product's
    // low half zero, one more with its high half zero too
    // (a memory operand's datum: the read delivered on this clock, the row reads it then)
    wire [16:0] mu_a = opnd(fmt.opa, fmt, op, ob, rd_now ? rd_dat : rd);
    wire [16:0] mu_b = opnd(fmt.opb, fmt, op, ob, rd_now ? rd_dat : rd);
    wire [31:0] mu_p = $signed(mu_a[15:0]) * $signed(mu_b[15:0]);
    assign mneg = (fmt.xop == V35_XOP_MUL && fmt.sgn && fmt.wd
                   && (mu_a[15] ^ mu_b[15]))
                  ? 4'd8 + (mu_p[15:0] == 16'd0 ? 4'd1 : 4'd0)
                    + ((mu_p[15:0] == 16'd0 && mu_p[31:16] == 16'd0) ? 4'd1 : 4'd0) : 4'd0;

    // ------------------------------------------------------------ a transfer's target
    // (S5a) the flush's address (the form after T: its operand bytes, its reads in order, the
    // register target latched at its take): REL the next instruction's offset + the
    // displacement (a byte sign-extended, or a word); FAR the operand's offset and segment;
    // REG tgt; MEM / MEMFAR the pointer's words; RET the return offset (far: and segment; RETI:
    // and the PSW); BRK the vector's offset and segment. A far target loads PS.
    logic [15:0] tg_off, tg_seg;
    logic        tg_far, tg_psw;
    wire  [15:0] ip_t = 16'(pc_t - {ps, 4'd0});
    always_comb begin
        tg_off = ip_t + 16'(f_t.len) + (f_t.tail == 3'd2 ? ob_t[15:0] : {{8{ob_t[7]}}, ob_t[7:0]});
        tg_seg = ps;
        tg_far = 1'b0;
        tg_psw = 1'b0;
        case (f_t.xop)
            V35_XOP_JMP, V35_XOP_CALL, V35_XOP_LOOP:
                case (f_t.aop)
                    V35_XK_FAR: begin
                        tg_off = ob_t[15:0];
                        tg_seg = ob_t[31:16];
                        tg_far = 1'b1;
                    end
                    V35_XK_REG: tg_off = tgt;
                    V35_XK_MEM: tg_off = rq0;
                    V35_XK_MEMFAR: begin
                        tg_off = rq0;
                        tg_seg = rq1;
                        tg_far = 1'b1;
                    end
                    default: ;
                endcase
            V35_XOP_RET: begin
                tg_off = rq0;
                if (f_t.aop != V35_RETK_NEAR) begin
                    tg_seg = rq1;
                    tg_far = 1'b1;
                end
                tg_psw = f_t.aop == V35_RETK_INT;
            end
            V35_XOP_BRK: begin
                tg_off = rq0;
                tg_seg = rq1;
                tg_far = 1'b1;
            end
            default: ;
        endcase
    end
    assign t_flush_addr = {tg_seg, 4'd0} + {4'd0, tg_off};

    // the SFR store's datum (a store_imm takes its immediate after the store issued)
    wire [16:0] sfr_v = opnd(fmt.opb, fmt, op, ob, rd);
    assign sfr_data = fmt.immb == 2'd1 ? {sfr_v[7:0], sfr_v[7:0]} : sfr_v[15:0];

    // ------------------------------------------------------------ S6: the writes
    // this clock's writes: the exec's (one or two registers, a segment register), the
    // stack pointer's, the divider's result; one goes to the RAM, a second waits a clock
    wire [2:0]  bank = psw[14:12];
    logic       c1_v, c2_v, c3_v;
    logic [6:0] c1_a, c2_a, c3_a;
    logic [1:0] c1_b, c2_b, c3_b;
    logic [15:0] c1_d, c2_d, c3_d;
    logic [20:0] wp;
    always_comb begin
        wp = 21'd0;
        c1_v = 1'b0; c1_a = 7'd0; c1_b = 2'd0; c1_d = 16'd0;
        c2_v = 1'b0; c2_a = 7'd0; c2_b = 2'd0; c2_d = 16'd0;
        c3_v = 1'b0; c3_a = 7'd0; c3_b = 2'd0; c3_d = 16'd0;
        if (ex_go && xr.w1) begin
            wp = wput(xr.r1, (xr.r1 == {1'b1, R_AW} && f_now.xop == V35_XOP_MUL) ? 1'b1
                             : (f_now.xop == V35_XOP_LAHF ? 1'b0 : f_now.wd), xr.v1);
            c1_v = 1'b1;
            c1_a = rword(bank, wp[20:18]);
            c1_b = wp[17:16];
            c1_d = wp[15:0];
        end else if (dfin && !dtrap) begin
            c1_v = 1'b1;
            c1_a = rword(bank, R_AW);
            c1_b = ds.w ? 2'b11 : 2'b11;
            c1_d = ds.w ? dres[15:0] : {dres[15:8], dres[7:0]};
        end
        if (ex_go && xr.w2) begin
            wp = wput(xr.r2, f_now.xop == V35_XOP_MUL ? 1'b1 : f_now.wd, xr.v2);
            c2_v = 1'b1;
            c2_a = rword(bank, wp[20:18]);
            c2_b = wp[17:16];
            c2_d = wp[15:0];
        end else if (ex_go && xr.sg) begin
            c2_v = 1'b1;
            c2_a = sword(bank, xr.sgi);
            c2_b = 2'b11;
            c2_d = xr.sgv;
        end else if (dfin && !dtrap && ds.w) begin
            c2_v = 1'b1;
            c2_a = rword(bank, R_DW);
            c2_b = 2'b11;
            c2_d = dres[31:16];
        end else if (t_flush && tg_far) begin
            c2_v = 1'b1;                // a far transfer's PS, stored through to its bank slot
            c2_a = sword(bank, 2'd1);
            c2_b = 2'b11;
            c2_d = tg_seg;
        end
        if (sp_post) begin
            c3_v = 1'b1;
            c3_a = rword(bank, R_SP);
            c3_b = 2'b11;
            c3_d = sp_new;
        end else if (t_flush && f_t.xop == V35_XOP_RET && f_t.immb != 2'd0) begin
            c3_v = 1'b1;                // (S5a) RET imm16: SP raised by the immediate
            c3_a = rword(bank, R_SP);
            c3_b = 2'b11;
            c3_d = sp_rd[15:0] + immv(f_t, ob_t);
        end
    end
    // the order: the pending second write, then this clock's; the rest pending (one)
    logic       wr_v, nw2_v, lost;
    logic [6:0] wr_a, nw2_a;
    logic [1:0] wr_b, nw2_b;
    logic [15:0] wr_d, nw2_d;
    always_comb begin
        wr_v = 1'b0; wr_a = 7'd0; wr_b = 2'd0; wr_d = 16'd0;
        nw2_v = 1'b0; nw2_a = 7'd0; nw2_b = 2'd0; nw2_d = 16'd0;
        lost = 1'b0;
        if (w2_v) begin
            wr_v = 1'b1; wr_a = w2_a; wr_b = w2_be; wr_d = w2_d;
            if (c1_v) begin
                nw2_v = 1'b1; nw2_a = c1_a; nw2_b = c1_b; nw2_d = c1_d;
                lost = c2_v || c3_v;
            end else if (c2_v) begin
                nw2_v = 1'b1; nw2_a = c2_a; nw2_b = c2_b; nw2_d = c2_d;
                lost = c3_v;
            end else if (c3_v) begin
                nw2_v = 1'b1; nw2_a = c3_a; nw2_b = c3_b; nw2_d = c3_d;
            end
        end else if (c1_v) begin
            wr_v = 1'b1; wr_a = c1_a; wr_b = c1_b; wr_d = c1_d;
            if (c2_v) begin
                nw2_v = 1'b1; nw2_a = c2_a; nw2_b = c2_b; nw2_d = c2_d;
                lost = c3_v;
            end else if (c3_v) begin
                nw2_v = 1'b1; nw2_a = c3_a; nw2_b = c3_b; nw2_d = c3_d;
            end
        end else if (c2_v) begin
            wr_v = 1'b1; wr_a = c2_a; wr_b = c2_b; wr_d = c2_d;
            if (c3_v) begin
                nw2_v = 1'b1; nw2_a = c3_a; nw2_b = c3_b; nw2_d = c3_d;
            end
        end else if (c3_v) begin
            wr_v = 1'b1; wr_a = c3_a; wr_b = c3_b; wr_d = c3_d;
        end
    end
    // (S5a) the string unit's write-through: on a clock nothing else writes, the stale one of
    // CW, IX, IY
    wire        lz_v = !wr_v && (dcw || dix || diy);
    wire [2:0]  lz_r = dcw ? R_CW : (dix ? R_IX : R_IY);
    wire [15:0] lz_d = dcw ? cw : (dix ? ix : iy);
    assign wa_en = ce && (wr_v || lz_v);
    assign wa_addr = wr_v ? wr_a : rword(bank, lz_r);
    assign wa_be = wr_v ? wr_b : 2'b11;
    assign wa_data = wr_v ? wr_d : lz_d;
    // the flops follow their RAM word's writes (the current bank: this clock's write and one
    // left pending, the later last)
    function automatic logic [15:0] follow(input logic [15:0] v, input logic [2:0] r);
        logic [15:0] o;
        logic [6:0] a;
        a = rword(bank, r);
        o = v;
        if (wr_v && wr_a == a)
            o = {wr_b[1] ? wr_d[15:8] : o[15:8], wr_b[0] ? wr_d[7:0] : o[7:0]};
        if (nw2_v && nw2_a == a)
            o = {nw2_b[1] ? nw2_d[15:8] : o[15:8], nw2_b[0] ? nw2_d[7:0] : o[7:0]};
        return o;
    endfunction
    function automatic logic wfull(input logic [2:0] r);
        wfull = (wr_v && wr_a == rword(bank, r) && wr_b == 2'b11)
                || (nw2_v && nw2_a == rword(bank, r) && nw2_b == 2'b11);
    endfunction
    // the steps: an element's post (T, P), a REP element done (the sequencer's strobe)
    wire        sstr = f_now.xop == V35_XOP_STR;
    wire [15:0] sstep = f_now.w ? 16'd2 : 16'd1;
    wire        ix_st = sstr && ((post_t && prow_t.asrc == V35_ASRC_STR_IX && !povr_t)
                                 || (post_p && prow_p.asrc == V35_ASRC_STR_IX && !povr_p));
    wire        iy_st = sstr && ((post_t && prow_t.asrc == V35_ASRC_STR_IY && !povr_t)
                                 || (post_p && prow_p.asrc == V35_ASRC_STR_IY && !povr_p));
    wire        cw_st = sstr && f_now.rep && edone;
    wire [15:0] cw_n = cw_st ? cw - 16'd1 : follow(cw, R_CW);
    wire [15:0] ix_n = ix_st ? (psw[V35_PSW_DIR] ? ix - sstep : ix + sstep) : follow(ix, R_IX);
    wire [15:0] iy_n = iy_st ? (psw[V35_PSW_DIR] ? iy - sstep : iy + sstep) : follow(iy, R_IY);
    // the REP loop's last element by count (CW = 1 before its step), the compare's exit on
    // its condition (REPE: not Z; REPNE: Z; REPC: not CY; REPNC: CY) at its read's delivery
    // (the running form: a REP loop's rows never share a clock with a start; a BCD string's
    // pairs (CL + 1) / 2)
    assign str_last = (fmt.xop == V35_XOP_STR && fmt.rep && cw == 16'd1)
                      || (fmt.xop == V35_XOP_BCD && {1'b0, bi} + 9'd1 == ({1'b0, cw[7:0]} + 9'd1) >> 1);
    wire        scmp_on = rd_now && fmt.xop == V35_XOP_STR && fmt.rep && !srd_ovr
                          && (fmt.aop == V35_STR_CMPM || (fmt.aop == V35_STR_CMPBK && !srd_iy));
    wire [16:0] s_aw = rget({1'b1, R_AW});
    wire [15:0] s_a = fmt.aop == V35_STR_CMPBK ? rd_dat : s_aw[15:0];
    wire [15:0] s_b = fmt.aop == V35_STR_CMPBK ? sdst : rd_dat;
    wire        cz = fmt.wd ? s_a == s_b : s_a[7:0] == s_b[7:0];
    wire        cc = fmt.wd ? s_a < s_b : s_a[7:0] < s_b[7:0];
    assign str_exit = scmp_on && (fmt.repc == 2'd0 ? !cz : fmt.repc == 2'd1 ? cz
                                  : fmt.repc == 2'd2 ? !cc : cc);
    assign cl_c = cw[7:0];
    assign cl_e = cw_n[7:0];
    // the PSW after this clock (the exec's, the divider's)
    // (S5a) RETI's PSW at its flush (the flags: MD and RB stay, as POP PSW's); BRK clears IE
    // and BRK at its flush
    wire [15:0] psw_n = (ex_go && xr.pw) ? xr.pv : dfin ? dpsw
                      : (t_flush && tg_psw) ? {psw[15:12], rq2[11:0]}
                      : (t_flush && f_t.xop == V35_XOP_BRK) ? psw & ~16'h0300 : psw;
    assign psw_c = psw;
    assign psw_e = psw_n;
    assign cw_c = cw;
    assign cw_e = cw_n;

    // the EA unit (v35_ea.sv): the base on port B, the index on port A, latched once read
    wire [7:0]  ear_now, ear_t;
    wire        ea_done_n;
    assign ear_t = v35_ea_regs(f_t.md, f_t.rm);
    wire [16:0] ea_b = rget(ear_now[3] ? {1'b1, ear_now[2:0]} : 4'd0);
    wire [16:0] ea_i = rget(ear_now[7] ? {1'b1, ear_now[6:4]} : 4'd0);
    wire [16:0] ea_bt = rget(ear_t[3] ? {1'b1, ear_t[2:0]} : 4'd0);
    wire [16:0] ea_it = rget(ear_t[7] ? {1'b1, ear_t[6:4]} : 4'd0);
    wire [16:0] xl_b = rget({1'b1, R_BW});
    wire [16:0] xl_a = rget({1'b1, R_AW});
    wire        ea_bp;
    wire [19:0] ea_phys;
    v35_ea ea (
        .clock, .reset_n, .ce,
        .f_t, .b_t(ob_t), .base_t(ea_bt), .index_t(ea_it), .sego(st_t ? pfx : seg_o),
        .ds1, .ps, .ss, .ds0,
        .f_now, .new_form, .aim_ea, .base_n(ea_b), .index_n(ea_i), .xl_bw(xl_b[15:0]),
        .xl_al(xl_a[7:0]),
        .regs_n(ear_now), .done_n(ea_done_n), .off(ea_off_w), .bp(ea_bp), .seg(ea_seg_w),
        .phys(ea_phys), .ok_t(ea_ok_t)
    );

    // the next clock's ports: the registers the next clock's form reads: the running form's
    // while it still reads them (its exec, a post, the divider's dividend), else the next
    // form's (the decode ahead)
    wire        exec_done_n = new_form ? ex_go : (exec_done || ex_go);
    wire        cur_e = run_e && !(aim_next && (delivery_form || exec_done_n)
                                   && !(ex_go && xr.dstart));
    v35_fmt_t   fx;
    logic [7:0] ox;
    logic [3:0] na, nb;
    logic       nea;
    logic [7:0] ear;
    always_comb begin
        fx = cur_e ? fmt_e : nf_fmt;
        ox = cur_e ? o_now : nf_op;
        if (cur_e && fx.has_modrm && nob_now != 3'd0)
            fx = f_now;
        na = 4'd0;
        nb = 4'd0;
        nea = 1'b0;
        ear = v35_ea_regs(fx.md, fx.rm);
        if (fx.stk)
            nb = {1'b1, R_SP};
        else if (fx.port == 2'd2)
            nb = {1'b1, R_DW};
        else if (fx.xop == V35_XOP_XLAT)
            nb = {1'b1, R_BW};
        // a memory operand's EA (ModR/M forms): the base on B, the index on A, until latched
        // (POP r/m: SP first, for its stack read; the EA's registers after its post)
        if (fx.mem && fx.has_modrm && fx.md != 2'd3 && !(cur_e && ea_done_n)
            && !(fx.stk && fx.xop == V35_XOP_POP && !(cur_e && sp_done_n))) begin
            nea = 1'b1;
            nb = ear[3] ? {1'b1, ear[2:0]} : 4'd0;
            na = ear[7] ? {1'b1, ear[6:4]} : 4'd0;
        end else begin
            na = wreg(role_reg(fx.opa, fx, ox), fx.wd);
            if (!na[3] || fx.xop == V35_XOP_PUSH || fx.xop == V35_XOP_OUT)
                na = fx.xop == V35_XOP_OUT ? {1'b1, R_AW} : wreg(role_reg(fx.opb, fx, ox), fx.wd);
            if (!nb[3])
                nb = wreg(role_reg(fx.opb, fx, ox), fx.wd);
            if (fx.xop == V35_XOP_MUL || fx.xop == V35_XOP_DIV || fx.xop == V35_XOP_CVTWL
                || fx.xop == V35_XOP_CVTBW || fx.xop == V35_XOP_ADJ || fx.xop == V35_XOP_CVTBD
                || fx.xop == V35_XOP_CVTDB)
                na = {1'b1, R_AW};
            // (S5a) the strings: AW (STM's datum, CMPM, LDM); DW on B (the port forms)
            if (fx.xop == V35_XOP_STR)
                na = {1'b1, R_AW};
            // (S5a) PREPARE / DISPOSE read BP; PUSH R the register its next word pushes
            if (fx.xop == V35_XOP_PREP || fx.xop == V35_XOP_DISP)
                na = {1'b1, R_BP};
            if (fx.xop == V35_XOP_PUSHR)
                na = {1'b1, cur_e ? nsp_n : 3'd0};
        end
        // DIV: the dividend's high half (DW) on the clock after its exec
        if (ex_go && xr.dstart)
            na = {1'b1, R_DW};
        if (!(cur_e || nf_v)) begin
            na = 4'd0;
            nb = 4'd0;
        end
    end
    assign ra_next = rword(psw_n[14:12], na[2:0]);
    assign rb_next = rword(psw_n[14:12], nb[2:0]);

    assign pc_o = pc;
    assign miss_o = lost;

    always_ff @(posedge clock) begin
        if (!reset_n) begin
            fmt <= '0;
            op <= 8'h00;
            pc <= 20'hFFFF0;
            pfx <= 3'd0;
            seg_o <= 3'd0;
            ob <= 48'd0;
            nob <= 3'd0;
            exec_done <= 1'b0;
            exec_pend <= 1'b0;
            aim_ea <= 1'b0;
            sp_done <= 1'b0;
            pa_r <= 4'd0;
            pb_r <= 4'd0;
            rd <= 16'd0;
            res <= 16'd0;
            psw <= 16'hF002;
            ds1 <= 16'd0;
            ds0 <= 16'd0;
            ss <= 16'd0;
            ps <= 16'hFFFF;
            cw <= 16'd0;
            w2_v <= 1'b0;
            dv <= 1'b0;
            ds <= '0;
        end else if (ce) begin
            fmt <= f_now;
            op <= o_now;
            pc <= pc_now;
            if (st_t || st_p) begin
                seg_o <= pfx;
                pfx <= f_now.seg;           // a prefix's segment for the next form (0: none)
            end
            ob <= ob_now;
            nob <= nob_now;
            if (new_form)
                exec_done <= ex_go;
            else if (ex_go)
                exec_done <= 1'b1;
            exec_pend <= ex_wait;
            aim_ea <= nea && (cur_e || nf_v);
            pa_r <= (cur_e || nf_v) ? na : 4'd0;
            pb_r <= (cur_e || nf_v) ? nb : 4'd0;
            if (rd_now)
                rd <= rd_dat;
            if (rd_half)
                rd_lo <= dlv_data[15:8];
            sp_done <= sp_done_n;
            if (ex_go && xr.rv)
                res <= xr.res;
            psw <= psw_n;
            if (ex_go && xr.sg) begin
                case (xr.sgi)
                    2'd0: ds1 <= xr.sgv;
                    2'd1: ps <= xr.sgv;
                    2'd2: ss <= xr.sgv;
                    default: ds0 <= xr.sgv;
                endcase
            end
            if (t_flush && tg_far)
                ps <= tg_seg;
            // (S5a) the form's reads in order; a register transfer's target
            if (new_form)
                nrd <= rd_now ? 4'd1 : 4'd0;
            else if (rd_now && nrd != 4'd15)
                nrd <= nrd + 4'd1;
            if (rd_now) begin
                case (new_form ? 4'd0 : nrd)
                    4'd0: rq0 <= rd_dat;
                    4'd1: rq1 <= rd_dat;
                    default: rq2 <= rd_dat;
                endcase
            end
            if (ex_go && xr.tg)
                tgt <= xr.tgv;
            nsp <= nsp_n;
            cw <= cw_n;
            ix <= ix_n;
            iy <= iy_n;
            dcw <= cw_st || (dcw && !wfull(R_CW) && !(lz_v && lz_r == R_CW));
            dix <= ix_st || (dix && !wfull(R_IX) && !(lz_v && lz_r == R_IX));
            diy <= iy_st || (diy && !wfull(R_IY) && !(lz_v && lz_r == R_IY));
            // the string read posted last ([IY]? an overrun?), CMPBK's [IY] datum
            if (post_t && prow_t.rkind == V35_RK_READ) begin
                srd_iy <= prow_t.asrc == V35_ASRC_STR_IY;
                srd_ovr <= povr_t;
            end else if (post_p && (prow_p.rkind == V35_RK_READ
                                    || prow_p.rkind == V35_RK_IO_READ)) begin
                srd_iy <= prow_p.asrc == V35_ASRC_STR_IY;
                srd_ovr <= povr_p;
            end else if (post_t && prow_t.rkind == V35_RK_IO_READ) begin
                srd_iy <= 1'b0;
                srd_ovr <= 1'b0;
            end
            if (rd_now && (fmt.xop == V35_XOP_BCD ? !srd_iy : srd_iy))
                sdst <= rd_dat;
            // the BCD string's pairs
            if (new_form) begin
                bi <= 8'd0;
                bcy <= 1'b0;
                bz <= 1'b1;
            end else begin
                if (fmt.xop == V35_XOP_BCD && edone)
                    bi <= bi + 1'b1;
                if (fmt.xop == V35_XOP_BCD && rd_now && srd_iy) begin
                    bcy <= bcd_r[9];
                    bres <= bcd_r[7:0];
                    bz <= bz && bcd_r[8];
                end
            end
            w2_v <= nw2_v;
            w2_a <= nw2_a;
            w2_be <= nw2_b;
            w2_d <= nw2_d;
            ds <= ds_n;
            dvp <= ex_go && xr.dstart;
            if (ex_go && xr.dstart) begin
                dv_d <= dv_op[15:0];
                dv_lo <= dv_aw[15:0];
            end
            if (dvp)
                dv <= !ds_n.trap;
            else if (dfin)
                dv <= 1'b0;
        end
    end

